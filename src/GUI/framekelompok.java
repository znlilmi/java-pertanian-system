    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String id_kelompok = jTextField5.getText().trim();
        try {
            // Validasi input
            if (id_kelompok.isEmpty()) {
                JOptionPane.showMessageDialog(this, "ID Kelompok harus diisi", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            // Periksa apakah data dengan ID Kelompok ada di database
            if (!crud.duplicateKey("kelompok_tani", "id_kelompok", id_kelompok)) {
                JOptionPane.showMessageDialog(this, "Data tidak ditemukan untuk ID Kelompok ini", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            // Konfirmasi sebelum menghapus
            int confirm = JOptionPane.showConfirmDialog(this, "Apakah Anda yakin ingin menghapus data ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                // Hapus data dari database
                crud.HapusDinamisKelompok(id_kelompok);
                JOptionPane.showMessageDialog(this, "Data berhasil dihapus");
                // Refresh data di tabel
                loaddata();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

