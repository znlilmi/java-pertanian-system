    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // Ambil data dari form
        String id_bibit = jTextField1.getText().trim();
        String nama_bibit = jTextField2.getText().trim();
        String jenis_bibit = jTextField3.getText().trim();
        String jumlahText = jTextField4.getText().trim();

        // Validasi input
        if (id_bibit.isEmpty() || nama_bibit.isEmpty() || jenis_bibit.isEmpty() || jumlahText.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Semua field harus diisi!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int jumlah;
        try {
            jumlah = Integer.parseInt(jumlahText); // Pastikan jumlah valid
            if (jumlah <= 0) {
                throw new NumberFormatException(); // Lempar error jika jumlah <= 0
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(null, "Jumlah harus berupa angka positif!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Cek kunci duplikat
        if (!crud.duplicateKey("bibit", "id_bibit", id_bibit)) {
            // Simpan data jika tidak ada duplikat
            crud.SimpanDinamisBibit(id_bibit, new String[]{nama_bibit}, new String[]{jenis_bibit}, new int[]{jumlah});
            JOptionPane.showMessageDialog(null, "Data berhasil disimpan");

            // Refresh tabel
            loaddata();
        } else {
            JOptionPane.showMessageDialog(null, "id_bibit sudah ada", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

