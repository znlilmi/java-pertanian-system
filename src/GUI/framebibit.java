    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // Pastikan ada baris yang dipilih
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Pilih baris yang ingin dihapus!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Ambil nilai id_kelompok dari kolom tertentu di JTable (asumsi kolom ke-0 berisi id_kelompok)
        String id_kelompok = jTable1.getValueAt(selectedRow, 0).toString();

        // Konfirmasi penghapusan
        int confirm = JOptionPane.showConfirmDialog(this, 
            "Apakah Anda yakin ingin menghapus data dengan ID Kelompok: " + id_kelompok + "?", 
            "Konfirmasi Hapus", 
            JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                // Cek apakah data dengan id_kelompok ada
                if (crud.duplicateKey("kelompok_tani", "id_kelompok", id_kelompok)) {
                    // Hapus data
                    crud.HapusDinamisKelompok(id_kelompok);
                    JOptionPane.showMessageDialog(this, "Data berhasil dihapus");

                    // Refresh tabel
                    loaddata();
                } else {
                    JOptionPane.showMessageDialog(this, "ID Kelompok tidak ditemukan!", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton4ActionPerformed

